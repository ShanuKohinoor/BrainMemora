import { GoogleGenAI } from "@google/genai";    // Tool used to communicate with Gemini




export const generateGeminiText = async (prompt:string):Promise<string>=>{

   // Get the Gemini API key from the .env file
    const apiKey = process.env.GEMINI_API_KEY
    if(!apiKey){
        throw new Error("Gemini API Key is missing")
    }

    // Create a Gemini client using the API key
    const brainMemoraAI = new GoogleGenAI({apiKey})

    // Send the prompt to Gemini and wait for its response
    const response = await brainMemoraAI.models.generateContent({
        model: "gemini-3.5-flash-lite",
        contents: prompt
    })
        // Check whether Gemini generated any text
    if (!response.text) {
        throw new Error("Gemini did not generate any text");
    }

        // Return the text generated by Gemini
        return response.text
}